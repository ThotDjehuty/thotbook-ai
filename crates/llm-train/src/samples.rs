//! Training examples from `polarway-learn` shards.
//!
//! `polarway-learn` watches the ThotBook research lakehouse, admits only the
//! rows carrying the owner's tenant id, and writes them as JSONL:
//!
//! ```json
//! {"tenant":"…","prompt":"…","completion":"…","concepts":["yang-mills"],
//!  "references":["2111.03038"],"source_id":"q-…","timestamp":"…"}
//! ```
//!
//! This module turns those lines into [`TrainingExample`]s. Two things it is
//! careful about:
//!
//! **The tenant is checked again here.** `polarway-learn` already refuses
//! foreign rows at admission and re-audits its own shards, but this crate is
//! the last gate before weights move. A shard is a file on disk: it can be
//! copied, merged or regenerated by something that is not the pipeline. A
//! sample whose tenant is not the one we were asked to train stops the load
//! with [`SampleError::ForeignTenant`] rather than being skipped, because
//! silently dropping it would make a mixed shard look like a short one.
//!
//! **Prompt tokens are masked.** Labels mark prompt positions with
//! [`IGNORE_LABEL`] so the loss is taken on the answer only; otherwise the
//! model is rewarded for reciting the question back.

use std::path::{Path, PathBuf};

use serde::Deserialize;
use tokenizers::Tokenizer;

use crate::dataset::{StreamingDataset, TrainingExample, IGNORE_LABEL};
use crate::error::TrainError;

/// What a sample is good for, as `polarway-learn` labels it.
///
/// The MCP's lakehouse records what the owner *asked*, not what it answered,
/// so a bare query row carries no supervised text. Training on one would
/// teach the model to complete a physics question with the MCP's own
/// bookkeeping. Those arrive as `Signal`: they schedule retraining, they do
/// not enter the loss.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum SampleKind {
    Supervised,
    /// The default, so a shard written before the field existed — all of
    /// which held bare query rows — is read as signal rather than silently
    /// trained on.
    #[default]
    Signal,
}

/// One line of a `polarway-learn` shard.
#[derive(Debug, Clone, Deserialize)]
pub struct OwnerSample {
    pub tenant: String,
    #[serde(default)]
    pub kind: SampleKind,
    pub prompt: String,
    pub completion: String,
    #[serde(default)]
    pub concepts: Vec<String>,
    #[serde(default)]
    pub references: Vec<String>,
    #[serde(default)]
    pub source_id: String,
    #[serde(default)]
    pub timestamp: String,
}

#[derive(Debug)]
pub enum SampleError {
    ForeignTenant {
        path: PathBuf,
        line: usize,
        expected: String,
        saw: String,
    },
    Malformed {
        path: PathBuf,
        line: usize,
        reason: String,
    },
}

impl std::fmt::Display for SampleError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::ForeignTenant {
                path,
                line,
                expected,
                saw,
            } => write!(
                f,
                "{}:{line}: sample belongs to {saw:?}, expected {expected:?} — refusing to train",
                path.display()
            ),
            Self::Malformed { path, line, reason } => {
                write!(f, "{}:{line}: {reason}", path.display())
            }
        }
    }
}

impl From<SampleError> for TrainError {
    fn from(e: SampleError) -> Self {
        TrainError::Dataset(e.to_string())
    }
}

/// What a load did, for the run's audit line.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct LoadReport {
    pub shards: usize,
    pub samples: usize,
    /// Question-only rows: counted, never trained on.
    pub signal_only: usize,
    /// Samples whose completion tokenised to nothing, so there was no
    /// supervised position left after masking the prompt.
    pub empty_completions: usize,
    pub truncated: usize,
}

/// Read every `*.jsonl` shard in `dir` that belongs to `tenant`.
///
/// Shards are read in sorted order so a run is reproducible: the accumulator
/// names them `samples-00000.jsonl`, `samples-00001.jsonl`, … and that is the
/// order the owner asked the questions in.
pub fn read_shards(dir: &Path, tenant: &str) -> Result<Vec<OwnerSample>, TrainError> {
    let mut paths: Vec<PathBuf> = std::fs::read_dir(dir)
        .map_err(|e| TrainError::Io {
            path: dir.to_path_buf(),
            source: e,
        })?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "jsonl"))
        .collect();
    paths.sort();

    let mut out = Vec::new();
    for path in &paths {
        let text = std::fs::read_to_string(path).map_err(|e| TrainError::Io {
            path: path.clone(),
            source: e,
        })?;
        for (i, line) in text.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() {
                continue;
            }
            let s: OwnerSample =
                serde_json::from_str(line).map_err(|e| SampleError::Malformed {
                    path: path.clone(),
                    line: i + 1,
                    reason: e.to_string(),
                })?;
            if s.tenant != tenant {
                return Err(SampleError::ForeignTenant {
                    path: path.clone(),
                    line: i + 1,
                    expected: tenant.to_string(),
                    saw: s.tenant,
                }
                .into());
            }
            out.push(s);
        }
    }
    Ok(out)
}

/// Tokenise one sample into a causal-LM example with the prompt masked.
///
/// The sequence is `prompt + "\n" + completion`. Labels are the same ids,
/// with every position that belongs to the prompt — and the separator —
/// replaced by [`IGNORE_LABEL`]. `trainer.rs` shifts by one for next-token
/// prediction, so the first completion token is still predicted from the last
/// prompt token.
pub fn tokenize(
    sample: &OwnerSample,
    tokenizer: &Tokenizer,
    max_seq_len: usize,
) -> Result<TrainingExample, TrainError> {
    let prompt = format!("{}\n", sample.prompt);
    let prompt_ids = tokenizer
        .encode(prompt.as_str(), false)
        .map_err(|e| TrainError::Dataset(format!("tokenising prompt: {e}")))?
        .get_ids()
        .to_vec();
    let completion_ids = tokenizer
        .encode(sample.completion.as_str(), false)
        .map_err(|e| TrainError::Dataset(format!("tokenising completion: {e}")))?
        .get_ids()
        .to_vec();

    let mut input_ids = prompt_ids.clone();
    input_ids.extend_from_slice(&completion_ids);

    let mut labels: Vec<u32> = vec![IGNORE_LABEL; prompt_ids.len()];
    labels.extend_from_slice(&completion_ids);

    // Truncate from the front of the prompt, not the back of the answer: the
    // answer is the part being supervised, so dropping it would leave an
    // example with nothing to learn from.
    if input_ids.len() > max_seq_len {
        let cut = input_ids.len() - max_seq_len;
        input_ids.drain(..cut);
        labels.drain(..cut);
    }

    Ok(TrainingExample { input_ids, labels })
}

/// Load the owner's shards into a dataset ready for [`crate::trainer::Trainer`].
pub fn load_owner_dataset(
    dir: &Path,
    tenant: &str,
    tokenizer_path: &Path,
    max_seq_len: usize,
    batch_size: usize,
) -> Result<(StreamingDataset, LoadReport), TrainError> {
    let tokenizer = Tokenizer::from_file(tokenizer_path)
        .map_err(|e| TrainError::Config(format!("tokenizer {}: {e}", tokenizer_path.display())))?;

    let samples = read_shards(dir, tenant)?;
    let shards = std::fs::read_dir(dir)
        .map(|rd| {
            rd.filter_map(|e| e.ok())
                .filter(|e| e.path().extension().is_some_and(|x| x == "jsonl"))
                .count()
        })
        .unwrap_or(0);

    let mut report = LoadReport {
        shards,
        ..Default::default()
    };
    let mut examples = Vec::new();
    for s in &samples {
        if s.kind != SampleKind::Supervised {
            report.signal_only += 1;
            continue;
        }
        let ex = tokenize(s, &tokenizer, max_seq_len)?;
        if ex.labels.iter().all(|&l| l == IGNORE_LABEL) {
            // Nothing supervised: the completion was empty, or truncation ate
            // it. Counted and skipped — a zero-signal example still costs a
            // forward pass.
            report.empty_completions += 1;
            continue;
        }
        if ex.input_ids.len() == max_seq_len {
            report.truncated += 1;
        }
        examples.push(ex);
    }
    report.samples = examples.len();

    Ok((
        StreamingDataset::from_examples(examples, batch_size),
        report,
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Write;

    fn tmpdir(tag: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("samples-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    fn write_shard(dir: &Path, name: &str, lines: &[&str]) {
        let mut f = std::fs::File::create(dir.join(name)).unwrap();
        for l in lines {
            writeln!(f, "{l}").unwrap();
        }
    }

    const MINE: &str = r#"{"tenant":"owner@example.org","kind":"supervised","prompt":"hermitian yang-mills","completion":"see 2111.03038","concepts":["yang-mills"],"references":["2111.03038"],"source_id":"q-1","timestamp":"2026-10-21T10:00:00Z"}"#;
    const SIGNAL: &str = r#"{"tenant":"owner@example.org","kind":"signal","prompt":"wheeler-dewitt factor ordering","completion":"[unanswered] no references found","concepts":["wheeler-dewitt"],"references":[],"source_id":"q-3","timestamp":"2026-10-21T10:00:00Z"}"#;
    const LEGACY: &str = r#"{"tenant":"owner@example.org","prompt":"q","completion":"[arxiv_search] 2 reference(s)","concepts":[],"references":[],"source_id":"q-0","timestamp":"t"}"#;
    const THEIRS: &str = r#"{"tenant":"rival@othercorp.com","prompt":"their private question","completion":"their answer","concepts":[],"references":[],"source_id":"q-2","timestamp":"2026-10-21T10:00:00Z"}"#;

    #[test]
    fn reads_the_owners_samples() {
        let d = tmpdir("own");
        write_shard(&d, "samples-00000.jsonl", &[MINE, MINE]);
        let s = read_shards(&d, "owner@example.org").unwrap();
        assert_eq!(s.len(), 2);
        assert_eq!(s[0].references, vec!["2111.03038"]);
        std::fs::remove_dir_all(d).unwrap();
    }

    #[test]
    fn a_foreign_sample_stops_the_load() {
        let d = tmpdir("foreign");
        // A shard that has been tampered with, or merged by hand.
        write_shard(&d, "samples-00000.jsonl", &[MINE, THEIRS]);
        let err = read_shards(&d, "owner@example.org").unwrap_err();
        let msg = err.to_string();
        assert!(msg.contains("rival@othercorp.com"), "{msg}");
        assert!(msg.contains("refusing to train"), "{msg}");
        std::fs::remove_dir_all(d).unwrap();
    }

    #[test]
    fn shards_are_read_in_order() {
        let d = tmpdir("order");
        write_shard(&d, "samples-00001.jsonl", &[MINE.replace("q-1", "q-second").as_str()]);
        write_shard(&d, "samples-00000.jsonl", &[MINE.replace("q-1", "q-first").as_str()]);
        let s = read_shards(&d, "owner@example.org").unwrap();
        assert_eq!(s[0].source_id, "q-first");
        assert_eq!(s[1].source_id, "q-second");
        std::fs::remove_dir_all(d).unwrap();
    }

    #[test]
    fn a_question_only_row_is_not_trained_on() {
        let d = tmpdir("kind");
        write_shard(&d, "samples-00000.jsonl", &[MINE, SIGNAL, LEGACY]);
        let tok = std::path::PathBuf::from(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../data/tokenizers/qwen3-tokenizer.json"
        ));
        if !tok.exists() {
            eprintln!("skipping: no tokenizer at {}", tok.display());
            std::fs::remove_dir_all(d).unwrap();
            return;
        }
        let (ds, report) =
            load_owner_dataset(&d, "owner@example.org", &tok, 512, 1).unwrap();
        // One supervised sample; the explicit signal row and the legacy row
        // with no `kind` are both left out of the loss.
        assert_eq!(report.samples, 1, "{report:?}");
        assert_eq!(report.signal_only, 2, "{report:?}");
        assert_eq!(ds.len(), 1);
        std::fs::remove_dir_all(d).unwrap();
    }

    #[test]
    fn the_prompt_half_is_masked() {
        let tok = std::path::PathBuf::from(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../data/tokenizers/qwen3-tokenizer.json"
        ));
        if !tok.exists() {
            return;
        }
        let tokenizer = Tokenizer::from_file(&tok).unwrap();
        let s: OwnerSample = serde_json::from_str(MINE).unwrap();
        let ex = tokenize(&s, &tokenizer, 512).unwrap();
        assert_eq!(ex.input_ids.len(), ex.labels.len());
        let masked = ex.labels.iter().filter(|&&l| l == IGNORE_LABEL).count();
        assert!(masked > 0, "the prompt must be masked");
        assert!(masked < ex.labels.len(), "the answer must not be");
        // every unmasked label matches its own token
        for (i, &l) in ex.labels.iter().enumerate() {
            if l != IGNORE_LABEL {
                assert_eq!(l, ex.input_ids[i], "labels must align with inputs");
            }
        }
    }

    #[test]
    fn malformed_json_names_the_line() {
        let d = tmpdir("bad");
        write_shard(&d, "samples-00000.jsonl", &[MINE, "{not json"]);
        let msg = read_shards(&d, "owner@example.org")
            .unwrap_err()
            .to_string();
        assert!(msg.contains(":2:"), "{msg}");
        std::fs::remove_dir_all(d).unwrap();
    }
}
